"""
Benchmark Report Generator.

Reads benchmark JSON results and produces a formatted Markdown report
with tables, ASCII degradation indicators, and recommendations.

Usage:
    python scripts/generate_benchmark_report.py
    python scripts/generate_benchmark_report.py --input results.json --output report.md
"""

import argparse
import json
import os
import sys
from pathlib import Path
from typing import Dict


# PRD target metrics for comparison
PRD_TARGETS = {
    "clean": 0.99,
    "jpeg_Q50": 0.85,
    "jpeg_Q30": 0.70,
    "screenshot": 0.80,
    "resize_scale0.5": 0.85,
    "crop_pct0.2": 0.75,
}


def _status_bar(value: float, width: int = 20) -> str:
    """Create an ASCII bar chart."""
    filled = int(value * width)
    return f"[{'█' * filled}{'░' * (width - filled)}] {value:.1%}"


def _status_emoji(rate: float, target: float) -> str:
    """Return status emoji based on rate vs target."""
    if rate >= target:
        return "✅"
    elif rate >= target * 0.8:
        return "⚠️"
    else:
        return "❌"


def generate_report(data: Dict, output_path: str) -> str:
    """Generate Markdown benchmark report.

    Args:
        data: Benchmark results dictionary (from benchmark runner).
        output_path: Path to write the Markdown report.

    Returns:
        The report as a string.
    """
    results = data["results"]
    meta = data["metadata"]

    lines = []
    lines.append("# PROVENA Trinity — Latent Watermark Benchmark Report")
    lines.append("")
    lines.append(f"**Generated**: {meta['timestamp']}")
    lines.append(f"**Images Tested**: {meta['num_images']}")
    lines.append(f"**Image Size**: {meta['image_size']}×{meta['image_size']}")
    lines.append(f"**Total Runtime**: {meta['total_time_seconds']:.1f}s")
    lines.append("")

    # ── Summary Table ─────────────────────────────────────────────
    lines.append("## Detection Rate Summary")
    lines.append("")
    lines.append("| Transform | Detection Rate | Avg Confidence | Latency (ms) | Status |")
    lines.append("|-----------|---------------|----------------|--------------|--------|")

    for key, r in results.items():
        rate = r["detection_rate"]
        target = PRD_TARGETS.get(key, 0.50)
        emoji = _status_emoji(rate, target)
        lines.append(
            f"| {key} | {rate:.1%} | {r['avg_confidence']:.3f} | "
            f"{r['avg_latency_ms']:.1f} | {emoji} |"
        )

    lines.append("")

    # ── Degradation Curves ────────────────────────────────────────
    lines.append("## Degradation Curves")
    lines.append("")

    # Group by transform type
    grouped: Dict[str, list] = {}
    for key, r in results.items():
        t = r["transform"]
        grouped.setdefault(t, []).append((key, r))

    for transform, entries in grouped.items():
        lines.append(f"### {transform.upper()}")
        lines.append("```")
        for key, r in entries:
            bar = _status_bar(r["detection_rate"])
            lines.append(f"  {key:30s} {bar}")
        lines.append("```")
        lines.append("")

    # ── PRD Target Comparison ─────────────────────────────────────
    lines.append("## PRD Target Comparison")
    lines.append("")
    lines.append("| Metric | Target | Actual | Status |")
    lines.append("|--------|--------|--------|--------|")

    for key, target in PRD_TARGETS.items():
        actual = results.get(key, {}).get("detection_rate", None)
        if actual is not None:
            emoji = _status_emoji(actual, target)
            lines.append(f"| {key} | {target:.0%} | {actual:.1%} | {emoji} |")
        else:
            lines.append(f"| {key} | {target:.0%} | N/A | ⬜ |")

    lines.append("")

    # ── Recommendations ───────────────────────────────────────────
    lines.append("## Recommendations")
    lines.append("")

    failures = []
    for key, target in PRD_TARGETS.items():
        actual = results.get(key, {}).get("detection_rate", None)
        if actual is not None and actual < target:
            failures.append((key, target, actual))

    if failures:
        lines.append("### Areas Needing Improvement:")
        for key, target, actual in failures:
            gap = target - actual
            lines.append(
                f"- **{key}**: {actual:.1%} vs target {target:.0%} "
                f"(gap: {gap:.1%}). Consider increasing embedding strength "
                f"or adding multi-band embedding."
            )
    else:
        lines.append("✅ All PRD targets met! System is performing as expected.")

    lines.append("")
    lines.append("---")
    lines.append("*Report generated by PROVENA Trinity Benchmark Suite*")

    report = "\n".join(lines)

    os.makedirs(os.path.dirname(output_path) or ".", exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as f:
        f.write(report)

    return report


def main():
    parser = argparse.ArgumentParser(description="Generate benchmark report")
    parser.add_argument(
        "--input",
        type=str,
        default="benchmarks/benchmark_results.json",
        help="Input JSON file",
    )
    parser.add_argument(
        "--output",
        type=str,
        default="benchmarks/BENCHMARK_REPORT.md",
        help="Output Markdown file",
    )
    args = parser.parse_args()

    if not os.path.exists(args.input):
        print(f"Error: {args.input} not found. Run the benchmark first.")
        sys.exit(1)

    with open(args.input) as f:
        data = json.load(f)

    report = generate_report(data, args.output)
    print(report)
    print(f"\n✓ Report saved to {args.output}")


if __name__ == "__main__":
    main()
